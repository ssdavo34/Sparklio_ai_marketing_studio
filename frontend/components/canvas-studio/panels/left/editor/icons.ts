/**
 * Icon ID로 찾기
 */
export function getIconById(iconId: string): IconConfig | undefined {
  return ALL_ICONS.find((icon) => icon.id === iconId);
}

/**
 * 카테고리별 아이콘 가져오기
 */
export function getIconsByCategory(category: IconCategory): IconConfig[] {
  return ALL_ICONS.filter((icon) => icon.category === category);
}

/**
 * SVG를 특정 색상으로 변환
 */
export function colorizeIconSvg(svg: string, color: string): string {
  return svg.replace(/stroke="currentColor"/g, `stroke="${color}"`).replace(/fill="currentColor"/g, `fill="${color}"`);
}

/**
 * SVG를 Data URI로 변환
 */
export function iconSvgToDataUri(svg: string, color: string = '#000000'): string {
  const coloredSvg = colorizeIconSvg(svg, color);
  return 'data:image/svg+xml;base64,' + btoa(coloredSvg);
}
